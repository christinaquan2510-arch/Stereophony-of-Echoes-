// Turns the Markdown files in /prompts into api/_prompts.js, which the server function imports.
// Run after editing any card or rule:  node scripts/build-prompts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (name) => {
  const text = readFileSync(join(root, "prompts", name), "utf8");
  // Drop the file's own header (title and status lines) above the first "---" divider.
  const i = text.indexOf("\n---\n");
  return (i === -1 ? text : text.slice(i + 5)).trim();
};

const out = {
  FOUNDING: read("founding-principle.md"),
  TABLE_RULES: read("table-rules.md"),
  HOST: read("barthes-host-card.md"),
  CARDS: {
    woolf: read("woolf-card.md"),
    plato: read("plato-card.md"),
    sushi: read("sushi-card.md"),
    freud: read("freud-card.md"),
    leonardo: read("leonardo-card.md"),
    einstein: read("einstein-card.md"),
    dickinson: read("dickinson-card.md"),
  },
};

writeFileSync(
  join(root, "api", "_prompts.js"),
  "// Generated by scripts/build-prompts.mjs. Edit the files in /prompts, then rerun the script.\n" +
    "export const PROMPTS = " + JSON.stringify(out, null, 2) + ";\n"
);
console.log("Wrote api/_prompts.js");
